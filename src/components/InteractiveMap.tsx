import React, { useMemo, useState } from 'react';
import {
  MapContainer,
  TileLayer,
  Polyline,
  Marker,
  Popup,
  useMap,
} from 'react-leaflet';
import L from 'leaflet';
import { NavigationRoute, LiveLocationData } from '../types';
import {
  Shield,
  MapPin,
  Eye,
  Sun,
  Users,
  ShieldAlert,
  Sparkles,
  Navigation,
  Layers,
  Compass,
} from 'lucide-react';

import 'leaflet/dist/leaflet.css';

interface InteractiveMapProps {
  routes: NavigationRoute[];
  selectedRouteId: string;
  onSelectRoute: (id: string) => void;
  userLocation: LiveLocationData;
  timeContext: 'daylight' | 'afternoon' | 'after_dark' | 'late_night';
}

/* Fix Leaflet marker icons when using Vite */
const createIcon = (color: string, emoji: string) =>
  L.divIcon({
    className: '',
    html: `
      <div style="
        width: 34px;
        height: 34px;
        border-radius: 50%;
        background: ${color};
        border: 3px solid white;
        display: flex;
        align-items: center;
        justify-content: center;
        font-size: 16px;
        box-shadow: 0 3px 12px rgba(0,0,0,0.4);
      ">
        ${emoji}
      </div>
    `,
    iconSize: [34, 34],
    iconAnchor: [17, 17],
  });

const startIcon = createIcon('#4f46e5', '📍');
const destinationIcon = createIcon('#db2777', '🏁');
const liveIcon = createIcon('#10b981', '●');
const safetyIcon = createIcon('#0284c7', '🛡️');

/* Automatically fit the map around the selected route */
const RouteFitter: React.FC<{
  coordinates: [number, number][];
}> = ({ coordinates }) => {
  const map = useMap();

  React.useEffect(() => {
    if (coordinates.length >= 2) {
      const bounds = L.latLngBounds(coordinates);

      map.fitBounds(bounds, {
        padding: [50, 50],
        maxZoom: 16,
      });
    } else if (coordinates.length === 1) {
      map.setView(coordinates[0], 15);
    }
  }, [coordinates, map]);

  return null;
};

export const InteractiveMap: React.FC<InteractiveMapProps> = ({
  routes,
  selectedRouteId,
  onSelectRoute,
  userLocation,
  timeContext,
}) => {
  const [activeLayer, setActiveLayer] = useState<
    'all' | 'lighting' | 'crowd' | 'crime'
  >('all');

  const selectedRoute =
    routes.find((r) => r.id === selectedRouteId) || routes[0];

  const isNight =
    timeContext === 'after_dark' || timeContext === 'late_night';

  /*
   * Convert our RouteCoordinate[] format into Leaflet's
   * [latitude, longitude] format.
   *
   * If coordinates haven't been generated by the routing API yet,
   * we temporarily use route waypoints.
   */
  const getRouteCoordinates = (
    route: NavigationRoute
  ): [number, number][] => {
    if (route.coordinates && route.coordinates.length >= 2) {
      return route.coordinates.map(
        (point) => [point.lat, point.lng] as [number, number]
      );
    }

    if (route.waypoints && route.waypoints.length >= 2) {
      return route.waypoints.map(
        (point) => [point.lat, point.lng] as [number, number]
      );
    }

    return [];
  };

  const selectedCoordinates = selectedRoute
    ? getRouteCoordinates(selectedRoute)
    : [];

  /*
   * Use the first available route coordinate as the initial
   * map center. If no route exists, use the user's GPS position.
   */
  const mapCenter: [number, number] =
    selectedCoordinates.length > 0
      ? selectedCoordinates[0]
      : [userLocation.latitude, userLocation.longitude];

  return (
    <div className="bg-[#23171F] text-white rounded-3xl p-5 shadow-md border border-[#F5A5BC]/30 relative overflow-hidden flex flex-col h-[520px]">

      {/* Top Map Toolbar */}
      <div className="flex flex-wrap items-center justify-between gap-3 z-10 mb-3">

        <div className="flex items-center gap-2.5">
          <div className="w-8 h-8 rounded-xl bg-[#E94F83]/20 border border-[#E94F83]/40 flex items-center justify-center text-[#F5A5BC]">
            <Compass className="w-4 h-4" />
          </div>

          <div>
            <div className="flex items-center gap-2">
              <span className="font-serif text-sm font-bold text-white tracking-tight">
                AuraSafe Live Road Map
              </span>

              <span
                className={`text-[10px] uppercase font-bold px-2 py-0.5 rounded-full ${
                  isNight
                    ? 'bg-[#E94F83]/20 text-[#F5A5BC] border border-[#E94F83]/30'
                    : 'bg-[#C88724]/20 text-[#C88724] border border-[#C88724]/30'
                }`}
              >
                {isNight ? 'Night Mode Activated' : 'Daylight View'}
              </span>
            </div>

            <p className="text-[11px] text-white/60">
              OpenStreetMap road network · Live safety corridor visualization
            </p>
          </div>
        </div>

        {/* Layer Selector */}
        <div className="flex items-center gap-1 bg-white/10 p-1 rounded-full border border-white/15 text-xs">

          <span className="text-[10px] text-white/60 px-2.5 font-semibold flex items-center gap-1">
            <Layers className="w-3 h-3" />
            Layer:
          </span>

          <button
            onClick={() => setActiveLayer('all')}
            className={`px-3 py-1 rounded-full font-semibold text-[11px] transition-all cursor-pointer ${
              activeLayer === 'all'
                ? 'bg-[#E94F83] text-white shadow-xs'
                : 'text-white/70 hover:text-white'
            }`}
          >
            Combined
          </button>

          <button
            onClick={() => setActiveLayer('lighting')}
            className={`px-3 py-1 rounded-full font-semibold text-[11px] flex items-center gap-1 transition-all cursor-pointer ${
              activeLayer === 'lighting'
                ? 'bg-[#C88724] text-white shadow-xs'
                : 'text-white/70 hover:text-white'
            }`}
          >
            <Sun className="w-3 h-3" />
            Lighting
          </button>

          <button
            onClick={() => setActiveLayer('crowd')}
            className={`px-3 py-1 rounded-full font-semibold text-[11px] flex items-center gap-1 transition-all cursor-pointer ${
              activeLayer === 'crowd'
                ? 'bg-[#E94F83] text-white shadow-xs'
                : 'text-white/70 hover:text-white'
            }`}
          >
            <Users className="w-3 h-3" />
            Crowds
          </button>

          <button
            onClick={() => setActiveLayer('crime')}
            className={`px-3 py-1 rounded-full font-semibold text-[11px] flex items-center gap-1 transition-all cursor-pointer ${
              activeLayer === 'crime'
                ? 'bg-[#D83B52] text-white shadow-xs'
                : 'text-white/70 hover:text-white'
            }`}
          >
            <ShieldAlert className="w-3 h-3" />
            Low Crime
          </button>

        </div>
      </div>

      {/* REAL OPENSTREETMAP MAP */}
      <div className="relative flex-1 rounded-2xl overflow-hidden border border-slate-800">

        <MapContainer
  center={mapCenter}
  zoom={14}
  scrollWheelZoom={true}
  className="h-full w-full"
  key={
    selectedRoute
      ? `${selectedRoute.id}-${selectedCoordinates[0]?.[0]}-${selectedCoordinates[0]?.[1]}-${selectedCoordinates[selectedCoordinates.length - 1]?.[0]}-${selectedCoordinates[selectedCoordinates.length - 1]?.[1]}`
      : 'default-map'
  }
>

          {/* OpenStreetMap tiles */}
          <TileLayer
            attribution='&copy; OpenStreetMap contributors'
            url="https://{s}.tile.openstreetmap.org/{z}/{x}/{y}.png"
          />

          {/* Fit map to selected route */}
          {selectedCoordinates.length >= 2 && (
            <RouteFitter coordinates={selectedCoordinates} />
          )}

          {/* ALL AVAILABLE ROUTES */}
          {routes.map((route) => {
            const coordinates = getRouteCoordinates(route);

            if (coordinates.length < 2) {
              return null;
            }

            const isSelected = route.id === selectedRouteId;

            const routeColor =
              route.safetyTier === 'SAFE'
                ? '#10b981'
                : route.safetyTier === 'MODERATE'
                ? '#f59e0b'
                : '#ef4444';

            return (
              <Polyline
                key={route.id}
                positions={coordinates}
                pathOptions={{
                  color: routeColor,
                  weight: isSelected ? 8 : 5,
                  opacity: isSelected ? 1 : 0.35,
                  dashArray:
                    route.safetyTier === 'CAUTION'
                      ? '10 8'
                      : undefined,
                }}
                eventHandlers={{
                  click: () => onSelectRoute(route.id),
                }}
              />
            );
          })}

          {/* PICKUP / START LOCATION */}
          {selectedCoordinates.length >= 1 && (
            <Marker
              position={selectedCoordinates[0]}
              icon={startIcon}
            >
              <Popup>
                <strong>Pickup / Starting Point</strong>
                <br />
                Your selected origin
              </Popup>
            </Marker>
          )}

          {/* DROP / DESTINATION LOCATION */}
          {selectedCoordinates.length >= 2 && (
            <Marker
              position={
                selectedCoordinates[selectedCoordinates.length - 1]
              }
              icon={destinationIcon}
            >
              <Popup>
                <strong>Drop / Destination</strong>
                <br />
                Your selected destination
              </Popup>
            </Marker>
          )}

          {/* LIVE GPS LOCATION */}
          <Marker
            position={[
              userLocation.latitude,
              userLocation.longitude,
            ]}
            icon={liveIcon}
          >
            <Popup>
              <strong>📍 You are here</strong>
              <br />
              Live GPS location
              <br />
              Accuracy: {Math.round(userLocation.accuracy)}m
            </Popup>
          </Marker>

          {/* Example safety point */}
          {selectedCoordinates.length >= 2 && (
            <Marker
              position={selectedCoordinates[
                Math.floor(selectedCoordinates.length / 2)
              ]}
              icon={safetyIcon}
            >
              <Popup>
                <strong>Safety Point</strong>
                <br />
                Nearby safety infrastructure
              </Popup>
            </Marker>
          )}

        </MapContainer>

        {/* Selected Route Card */}
        {selectedRoute && (
          <div className="absolute left-4 bottom-4 z-[1000] bg-slate-900/95 backdrop-blur-md border border-slate-700/80 rounded-2xl p-3 text-xs max-w-xs shadow-xl hidden sm:block">

            <div className="flex items-center justify-between gap-2 mb-1.5">

              <span className="font-extrabold text-white text-xs truncate">
                {selectedRoute.name}
              </span>

              <span
                className={`px-2 py-0.5 rounded-md font-black text-[10px] uppercase ${
                  selectedRoute.safetyTier === 'SAFE'
                    ? 'bg-emerald-500/20 text-emerald-300 border border-emerald-500/40'
                    : selectedRoute.safetyTier === 'MODERATE'
                    ? 'bg-amber-500/20 text-amber-300 border border-amber-500/40'
                    : 'bg-rose-500/20 text-rose-300 border border-rose-500/40'
                }`}
              >
                Score {selectedRoute.overallScore}/100
              </span>

            </div>

            <p className="text-[11px] text-slate-400 line-clamp-2">
              {selectedRoute.tagline}
            </p>

            <div className="mt-2 flex items-center gap-3 text-[10px] text-slate-400">
              <span>
                📏 {selectedRoute.distanceKm} km
              </span>

              <span>
                ⏱️ {selectedRoute.estimatedMinutes} min
              </span>
            </div>
          </div>
        )}

        {/* Map info badge */}
        <div className="absolute right-4 top-4 z-[1000] bg-slate-900/90 backdrop-blur border border-slate-700 rounded-xl px-3 py-2 text-[10px] text-slate-300 shadow-lg">
          🗺️ OpenStreetMap
        </div>

      </div>
    </div>
  );
};

